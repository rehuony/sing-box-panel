func prepareNewSubscriptionToken(token SubscriptionToken) (SubscriptionToken, error) {
	if err := validateSubscriptionID(token.ID, "token"); err != nil {
		return SubscriptionToken{}, err
	}
	digest, err := normalizeTokenDigest(token.TokenSHA256)
	if err != nil {
		return SubscriptionToken{}, err
	}
	if token.ChannelID != "" {
		if err := validateSubscriptionID(token.ChannelID, "channel"); err != nil {
			return SubscriptionToken{}, err
		}
	}
	createdAt := token.CreatedAt
	if createdAt.IsZero() {
		createdAt = time.Now().UTC()
	} else {
		createdAt = createdAt.UTC()
	}
	if token.ExpiresAt != nil {
		expiresAt := token.ExpiresAt.UTC()
		if !expiresAt.After(createdAt) {
			return SubscriptionToken{}, errors.New("subscription token expiry must follow creation")
		}
		token.ExpiresAt = &expiresAt
	}
	if token.RevokedAt != nil {
		return SubscriptionToken{}, errors.New("new subscription token cannot be revoked")
	}
	token.TokenSHA256 = digest
	token.CreatedAt = createdAt
	return token, nil
}

func canonicalChannelConfig(raw json.RawMessage) (json.RawMessage, error) {
	config, err := DecodeSubscriptionChannelConfig(raw)
	if err != nil {
		return nil, err
	}
	encoded, err := json.Marshal(config)
	if err != nil {
		return nil, fmt.Errorf("encode subscription channel config: %w", err)
	}
	return encoded, nil
}

func strictJSONObject(raw json.RawMessage, maximum int64, fallback string) (json.RawMessage, error) {
	if len(raw) == 0 {
		raw = json.RawMessage(fallback)
	}
	var value map[string]any
	if err := jsonstrict.Decode(raw, maximum, &value); err != nil {
		return nil, err
	}
	if value == nil {
		return nil, errors.New("value must be a non-null JSON object")
	}
	encoded, err := json.Marshal(value)
	if err != nil {
		return nil, fmt.Errorf("encode JSON object: %w", err)
	}
	return bytes.Clone(encoded), nil
}

func strictSourceSnapshot(raw json.RawMessage) (json.RawMessage, error) {
	if len(raw) == 0 {
		return nil, errors.New("subscription source snapshot is empty")
	}
	var value any
	if err := jsonstrict.Decode(raw, maximumSourceSnapshotBytes, &value); err != nil {
		return nil, fmt.Errorf("subscription source snapshot: %w", err)
	}
	switch value.(type) {
	case map[string]any, []any:
	default:
		return nil, errors.New("subscription source snapshot must be a JSON object or array")
	}
	encoded, err := json.Marshal(value)
	if err != nil {
		return nil, fmt.Errorf("encode subscription source snapshot: %w", err)
	}
	return bytes.Clone(encoded), nil
}

